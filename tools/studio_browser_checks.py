"""Shared browser checks for the real practice studio, without a backend."""
from playwright.sync_api import expect


def check_studio(page, media_dir=None):
    panel=page.locator('.transcription')
    expect(panel.locator('.note-block')).to_have_count(12)
    expect(panel.get_by_label('Playback instrument')).to_contain_text('Grand piano')
    page.wait_for_function("!document.querySelector('[aria-label=\"Playback instrument\"]').textContent.includes('loading')")
    # Reproduce changing tempo on Try chord example without pressing Stop/Play.
    panel.get_by_label('Loop practice section').check()
    panel.get_by_role('button',name='Play detected notes',exact=True).click()
    page.wait_for_function('cadenceAudio.at(-1)?.currentTime > .05 && !cadenceAudio.at(-1).paused')
    player_count=page.evaluate('cadenceAudio.length')
    selected_duration=float(panel.get_by_label('Loop end',exact=True).input_value())
    panel.get_by_label('Practice tempo').fill('50')
    assert page.evaluate('cadenceAudio.length')==player_count
    assert page.evaluate('!cadenceAudio.at(-1).paused && cadenceAudio.at(-1).playbackRate === .5')
    before=page.evaluate('cadenceAudio.at(-1).currentTime')
    page.wait_for_timeout(500)
    elapsed=page.evaluate('cadenceAudio.at(-1).currentTime')-before
    assert .12 < elapsed < .4, elapsed
    panel.get_by_label('Practice tempo').fill('200')
    assert page.evaluate('!cadenceAudio.at(-1).paused && cadenceAudio.at(-1).playbackRate === 2')
    panel.get_by_role('button',name='Stop notes',exact=True).click()
    panel.get_by_role('button',name='Play detected notes',exact=True).click()
    page.wait_for_function('cadenceAudio.at(-1)?.duration > 0 && !cadenceAudio.at(-1).paused')
    # Fresh playback renders at the selected tempo, with no accidental second scaling.
    assert abs(page.evaluate('cadenceAudio.at(-1).duration')-selected_duration/2)<.005
    assert page.evaluate('cadenceAudio.at(-1).playbackRate')==1
    panel.get_by_role('button',name='Stop notes',exact=True).click()
    panel.get_by_label('Practice tempo').fill('100')
    panel.get_by_label('Loop practice section').uncheck()
    panel.locator('.note-block').first.click()
    panel.get_by_label('Detected note pitch').fill('61')
    panel.get_by_role('button',name='Apply correction',exact=True).click()
    expect(panel.locator('.note-block').first).to_have_attribute('aria-label','Edit note 1: C♯4, 0.01 seconds')
    panel.get_by_role('button',name='Undo',exact=True).click()
    expect(panel.locator('.note-block').first).to_have_attribute('aria-label','Edit note 1: C4, 0.01 seconds')
    panel.get_by_role('button',name='Redo',exact=True).click()
    expect(panel.locator('.note-block').first).to_have_attribute('aria-label','Edit note 1: C♯4, 0.01 seconds')
    # Actual pointer drag is a single undoable edit.
    note=panel.locator('.note-block').first
    box=note.bounding_box()
    page.mouse.move(box['x']+box['width']/2,box['y']+box['height']/2)
    page.mouse.down();page.mouse.move(box['x']+box['width']/2+24,box['y']+box['height']/2-16,steps=5);page.mouse.up()
    assert note.get_attribute('aria-label')!='Edit note 1: C♯4, 0.01 seconds'
    panel.get_by_role('button',name='Undo',exact=True).click()
    expect(note).to_have_attribute('aria-label','Edit note 1: C♯4, 0.01 seconds')
    panel.get_by_role('button',name='Original audio',exact=True).click()
    panel.get_by_label('Playback speed').select_option('0.5')
    panel.get_by_role('button',name='Play original',exact=True).click()
    page.wait_for_function('cadenceAudio.at(-1)?.currentTime > .1 && !cadenceAudio.at(-1).paused')
    assert page.evaluate('cadenceAudio.at(-1).playbackRate')==.5
    panel.get_by_role('button',name='Stop notes',exact=True).click()
    panel.get_by_role('button',name='Detected notes',exact=True).click()
    panel.get_by_label('Loop practice section').check()
    panel.get_by_label('Loop start',exact=True).fill('0.2')
    panel.get_by_label('Loop end',exact=True).fill('0.6')
    panel.get_by_role('button',name='Play detected notes',exact=True).click()
    page.wait_for_function('cadenceAudio.at(-1)?.currentTime > .1 && !cadenceAudio.at(-1).paused')
    page.wait_for_timeout(1200)
    assert page.evaluate('!cadenceAudio.at(-1).paused')
    panel.get_by_role('button',name='Stop notes',exact=True).click()
    # Tempo changes shorten notes and the loop together; native repeat owns the seam.
    panel.get_by_label('Playback speed').select_option('1')
    panel.get_by_label('Practice tempo').fill('200')
    panel.get_by_label('Metronome during playback').check()
    panel.get_by_role('button',name='Play detected notes',exact=True).click()
    page.wait_for_function('cadenceAudio.at(-1)?.duration > 0 && !cadenceAudio.at(-1).paused')
    assert page.evaluate('cadenceAudio.at(-1).loop')
    # .4s at 2x is .2s, padded to one .3s metronome beat.
    assert abs(page.evaluate('cadenceAudio.at(-1).duration')-.3)<.002
    page.wait_for_timeout(1000)
    assert page.evaluate('!cadenceAudio.at(-1).paused && cadenceAudio.at(-1).currentTime < .301')
    panel.get_by_role('button',name='Stop notes',exact=True).click()
    panel.get_by_label('Count-in beats').select_option('4')
    panel.get_by_role('button',name='Play detected notes',exact=True).click()
    page.wait_for_function('cadenceAudio.at(-2)?.loop && cadenceAudio.at(-2)?.muted')
    page.wait_for_function('!cadenceAudio.at(-2).muted && !cadenceAudio.at(-2).paused')
    assert page.evaluate('cadenceAudio.at(-1).paused')
    page.wait_for_timeout(700)
    assert page.evaluate('!cadenceAudio.at(-2).paused')
    panel.get_by_role('button',name='Stop notes',exact=True).click()
    panel.get_by_label('Metronome during playback').uncheck()
    panel.get_by_label('Loop practice section').uncheck()
    panel.get_by_label('Practice tempo').fill('120')
    panel.get_by_label('Playback speed').select_option('1')
    panel.get_by_label('Count-in beats').select_option('4')
    panel.get_by_role('button',name='Play detected notes',exact=True).click()
    page.wait_for_function('cadenceAudio.at(-1)?.duration > 2 && !cadenceAudio.at(-1).paused')
    panel.get_by_role('button',name='Stop notes',exact=True).click()
    panel.get_by_label('Count-in beats').select_option('0')
    panel.get_by_role('button',name='Metronome only',exact=True).click()
    page.wait_for_function('cadenceAudio.at(-1)?.currentTime > .1 && !cadenceAudio.at(-1).paused')
    panel.get_by_role('button',name='Stop notes',exact=True).click()
    panel.get_by_role('tab',name='Sheet music',exact=True).click()
    expect(panel.locator('.sheet-canvas svg')).to_be_visible(timeout=15000)
    expect(panel.locator('.sheet-view')).to_contain_text('4/4 assumed')
    assert panel.locator('.sheet-canvas svg path').count()>5
    if media_dir:
        page.evaluate('window.scrollTo(0,0);document.activeElement.blur()')
        page.screenshot(path=str(media_dir/'sheet-music.png'),full_page=True)
    panel.get_by_role('tab',name='Piano roll',exact=True).click()
    panel.get_by_label('Session name',exact=True).fill('Studio regression')
    panel.get_by_role('button',name='Save session',exact=True).click()
    expect(panel.locator('.transcription-result')).to_contain_text('Saved on this device')
    page.reload()
    panel=page.locator('.transcription')
    expect(panel.get_by_label('Session name')).to_have_value('Studio regression')
    expect(panel.locator('.note-block').first).to_have_attribute('aria-label','Edit note 1: C♯4, 0.01 seconds')
    # Autosave a correction, then reopen through the actual library.
    panel.locator('.note-block').first.click()
    panel.get_by_label('Detected note pitch').fill('62')
    panel.get_by_role('button',name='Apply correction',exact=True).click()
    expect(panel.locator('.transcription-result')).to_contain_text('Saved on this device')
    page.get_by_role('button',name='Saved sessions',exact=True).click()
    expect(page.locator('.session-list')).to_contain_text('Studio regression')
    expect(page.locator('.session-list')).to_contain_text('Original audio included')
    page.get_by_role('button',name='Open session',exact=True).click()
    panel=page.locator('.transcription')
    expect(panel.locator('.note-block').first).to_have_attribute('aria-label','Edit note 1: D4, 0.01 seconds')
    panel.get_by_role('button',name='Undo all edits',exact=True).click()
    expect(panel.locator('.note-block').first).to_have_attribute('aria-label','Edit note 1: C4, 0.01 seconds')
    page.get_by_role('button',name='Saved sessions',exact=True).click()
    page.once('dialog',lambda dialog:dialog.accept())
    page.get_by_role('button',name='Delete session Studio regression',exact=True).click()
    expect(page.locator('.session-list li')).to_have_count(0)
    page.wait_for_timeout(750)
    expect(page.locator('.session-list li')).to_have_count(0)
    page.get_by_role('button',name='Piano studio',exact=True).click()
    print('PASS: original comparison, speed, loops, count-in, metronome, dragging, undo/redo, notation, IndexedDB save/reload/open/delete')
